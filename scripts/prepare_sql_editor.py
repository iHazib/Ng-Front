"""Package existing migrations without connecting to a database."""
from pathlib import Path
import hashlib
import json
import re

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'supabase/sql-editor'

def prepare():
    OUT.mkdir(parents=True, exist_ok=True)
    # The already-applied bootstrap remains immutable when incremental stages are added.
    files = [p for p in sorted((ROOT / 'supabase/migrations').glob('*.sql')) if p.name[:12] <= '202610050006']
    assert len(files) == 6
    texts = [p.read_text(encoding='utf-8') for p in files]
    tables = re.findall(r'create table public\.(\w+)', '\n'.join(texts))
    functions = sorted(set(re.findall(r'create (?:or replace )?function public\.(\w+)', '\n'.join(texts))))
    enums = re.findall(r'create type public\.(\w+)', '\n'.join(texts))
    literals = lambda values: ','.join("'" + v + "'" for v in values)
    preflight = """-- Read-only prerequisites. Stop on any exception; never drop objects to bypass it.
do $preflight$ begin
  if current_setting('server_version_num')::integer < 150000 then raise exception 'PostgreSQL 15+ required'; end if;
  if current_setting('server_encoding') <> 'UTF8' then raise exception 'UTF8 required'; end if;
  if to_regclass('auth.users') is null or to_regprocedure('auth.uid()') is null
     or to_regclass('storage.buckets') is null or to_regclass('storage.objects') is null then
    raise exception 'Actual Supabase Auth/Storage schema prerequisites missing'; end if;
  if not exists(select 1 from pg_roles where rolname='anon') or not exists(select 1 from pg_roles where rolname='authenticated') then raise exception 'Supabase roles missing'; end if;
  if exists(select 1 from pg_namespace where nspname='app_private') then raise exception 'app_private already exists: stop and inspect; no automatic overwrite'; end if;
  if exists(select 1 from pg_class where relnamespace='public'::regnamespace and relname in (__TABLES__)) then raise exception 'Nook and Glow table name collision: stop; preserve existing data'; end if;
  if exists(select 1 from pg_type where typnamespace='public'::regnamespace and typname in (__ENUMS__)) then raise exception 'Catalog type collision'; end if;
  if exists(select 1 from pg_proc where pronamespace='public'::regnamespace and proname in (__FUNCTIONS__)) then raise exception 'Catalog function name collision'; end if;
  if exists(select 1 from pg_extension e join pg_namespace n on n.oid=e.extnamespace where e.extname='pg_trgm' and n.nspname<>'extensions') then raise exception 'pg_trgm installed outside extensions; review compatibility without relocating automatically'; end if;
  if exists(select 1 from storage.buckets where id='catalog-private') then raise exception 'catalog-private bucket already exists; stop without changing it'; end if;
  if exists(select 1 from pg_policies where schemaname='storage' and tablename='objects') then raise exception 'Existing Storage policies require manual scope review before adding this bucket; do not delete policies'; end if;
end $preflight$;
""".replace('__TABLES__', literals(tables)).replace('__ENUMS__', literals(enums)).replace('__FUNCTIONS__', literals(functions))
    (OUT / '00_preflight.sql').write_text(preflight + "select 'PREFLIGHT PASSED; confirm this is your development project before installation' as result;\n", encoding='utf-8')
    manifest = [{'file':p.name, 'sha256':hashlib.sha256(p.read_bytes()).hexdigest()} for p in files]
    bundle = ['-- Generated by scripts/prepare_sql_editor.py. Run the ENTIRE file once in a development project.',
              '-- No catalog products/imports, Auth users, payments or shipments are created.',
              'begin;', "set local lock_timeout='5s';", "set local statement_timeout='120s';", 'select pg_advisory_xact_lock(73523);', preflight]
    for p, text in zip(files, texts):
        bundle += ['\n-- BEGIN '+p.name, text, '-- END '+p.name]
    bundle += ["create table app_private.sql_editor_receipts(version text primary key, filename text not null, sha256 text not null, applied_at timestamptz not null default now());",
               'alter table app_private.sql_editor_receipts enable row level security;',
               'revoke all on app_private.sql_editor_receipts from public,anon,authenticated;']
    for row in manifest:
        bundle += ["insert into app_private.sql_editor_receipts(version,filename,sha256) values ('"+row['file'].split('_')[0]+"','"+row['file']+"','"+row['sha256']+"');"]
    bundle += ["notify pgrst, 'reload schema';", 'commit;', "select 'ALL SIX MIGRATIONS COMMITTED' as result;"]
    (OUT / '01_install_all_six.sql').write_text('\n'.join(bundle)+'\n', encoding='utf-8')
    post = """-- Read-only metadata and role smoke checks; no data writes.
select version,filename,sha256 from app_private.sql_editor_receipts order by version;
select c.relname,c.relrowsecurity,
 has_table_privilege('anon',c.oid,'SELECT') as anon_select,
 has_table_privilege('authenticated',c.oid,'SELECT') as authenticated_select
from pg_class c where c.relnamespace='public'::regnamespace and c.relname in (__TABLES__) order by c.relname;
select has_schema_privilege('anon','public','USAGE') as anon_public_usage,
 has_schema_privilege('authenticated','public','USAGE') as authenticated_public_usage,
 has_schema_privilege('anon','app_private','USAGE') as anon_private_usage,
 has_schema_privilege('authenticated','app_private','USAGE') as user_private_usage;
select schemaname,tablename,policyname,roles,cmd from pg_policies
where schemaname='public' and tablename in (__TABLES__) or schemaname='storage' and policyname like 'ng_private_%'
order by schemaname,tablename,policyname;
select id,public from storage.buckets where id='catalog-private';
begin;
set local role anon;
select count(*) as anonymous_visible_products from public.products;
select public.is_admin() as anonymous_is_admin;
rollback;
begin;
set local role authenticated;
select set_config('request.jwt.claim.sub','00000000-0000-0000-0000-000000000000',true);
select public.is_admin() as unprovisioned_is_admin;
select count(*) as unprovisioned_visible_products from public.products;
rollback;
-- Counts should be zero after schema-only installation. This is SQL role simulation,
-- not real Auth login, JWT validation or HTTP Storage verification.
""".replace('__TABLES__', literals(tables))
    (OUT / '02_verify_installation.sql').write_text(post, encoding='utf-8')
    (OUT / '03_reload_schema_cache.sql').write_text("-- Safe cache notification, no data mutation. Run after checking schema and grants.\nNOTIFY pgrst, 'reload schema';\n", encoding='utf-8')
    (OUT / 'manifest.json').write_text(json.dumps({'migrations':manifest,'public_table_count':len(tables),'bundle_sha256':hashlib.sha256((OUT/'01_install_all_six.sql').read_bytes()).hexdigest()},indent=2)+'\n',encoding='utf-8')
    print('Prepared preflight, atomic six-migration installer, postflight and cache reload; no connection made.')

if __name__ == '__main__':
    prepare()
